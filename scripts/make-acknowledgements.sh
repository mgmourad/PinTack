#!/bin/zsh
# Builds ACKNOWLEDGEMENTS.md from the licence files the vendoring scripts write, and puts a copy
# inside the app bundle's resources so it ships with the app.
#
#   scripts/make-acknowledgements.sh
#
# MIT and the other permissive licences require the copyright notice and the licence text to travel
# with the software. That is not optional, and it is the reason this file exists rather than a list
# of names. A self-test check fails the build if the copy in the app and the copy in the repository
# ever drift apart.
set -euo pipefail
cd "$(dirname "$0")/.."
out=ACKNOWLEDGEMENTS.md
{
  echo "# Acknowledgements"
  echo
  echo "PinTack is free software under the GNU General Public License, version 3 or later (see LICENSE). It"
  echo "includes the third-party components below, each under a permissive and GPL-compatible licence,"
  echo "reproduced in full as those licences require."
  echo
  echo "Generated by \`scripts/make-acknowledgements.sh\`; edit the sources, not this file."
  echo
  echo "---"
  echo
  sed '1{/^# Third-party licenses$/d;}' Editor/vendor/LICENSES.md
  echo
  echo "---"
  echo
  cat Editor/icons/LICENSE.md
} > "$out"
mkdir -p PinTack/Resources
cp "$out" PinTack/Resources/ACKNOWLEDGEMENTS.md
echo "wrote $out and PinTack/Resources/ACKNOWLEDGEMENTS.md ($(wc -l < "$out") lines)"

# GPL-3.0 §4: a copy of the licence has to go to everyone who receives the program, so it ships
# inside the bundle rather than only sitting in the repository. Kept in step here so the two cannot
# drift apart.
cp LICENSE PinTack/Resources/LICENSE.txt
echo "wrote PinTack/Resources/LICENSE.txt"
